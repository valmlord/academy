/**
 * Schema v1 (ADR-0007). One FK chain users -> enrollments -> lesson_progress -> attempts ->
 * {check_results, mentor_reviews}, every FK ON DELETE CASCADE. Lessons are referenced by
 * (course_id, lesson_id) from course/ (ADR-0001), never through a lessons table. Every constraint and
 * index is named, so a later migration can drop or replace it by name. Column names are explicit
 * snake_case (no `casing` option), which survives the Drizzle 1.0 upgrade.
 */
import type { Check } from "@academy/lesson-schema";
import { sql } from "drizzle-orm";
import {
  boolean,
  check,
  doublePrecision,
  foreignKey,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";
import {
  ATTEMPT_STATUSES,
  CHECK_KINDS,
  CHECK_RESULT_STATUSES,
  inList,
  LESSON_PROGRESS_STATUSES,
  MENTOR_REVIEW_STATUSES,
} from "./vocabulary.js";

const createdAt = () => timestamp("created_at", { withTimezone: true }).notNull().defaultNow();

/**
 * Better Auth's core `user` model (#30 wires it under this key). The id is generated by the
 * application, as Better Auth does by default, so it has no DB default.
 */
export const users = pgTable(
  "users",
  {
    id: text("id").primaryKey(),
    name: text("name").notNull(),
    email: text("email").notNull(),
    emailVerified: boolean("email_verified").notNull().default(false),
    image: text("image"),
    createdAt: createdAt(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check("users_id_check", sql`${t.id} <> ''`),
    // Case-sensitive on purpose for v1; #30 checks whether Better Auth lowercases emails.
    unique("users_email_unique").on(t.email),
  ],
);

export const enrollments = pgTable(
  "enrollments",
  {
    userId: text("user_id").notNull(),
    courseId: text("course_id").notNull(),
    enrolledAt: timestamp("enrolled_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    primaryKey({ name: "enrollments_pkey", columns: [t.userId, t.courseId] }),
    foreignKey({
      name: "enrollments_user_id_fk",
      columns: [t.userId],
      foreignColumns: [users.id],
    }).onDelete("cascade"),
    check("enrollments_course_id_check", sql`${t.courseId} <> ''`),
  ],
);

export const lessonProgress = pgTable(
  "lesson_progress",
  {
    userId: text("user_id").notNull(),
    courseId: text("course_id").notNull(),
    lessonId: text("lesson_id").notNull(),
    status: text("status", { enum: LESSON_PROGRESS_STATUSES }).notNull().default("in-progress"),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull().defaultNow(),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    // The PK is the "progress unique per user+lesson" rule and serves per-user reads by prefix.
    primaryKey({ name: "lesson_progress_pkey", columns: [t.userId, t.courseId, t.lessonId] }),
    foreignKey({
      name: "lesson_progress_enrollment_fk",
      columns: [t.userId, t.courseId],
      foreignColumns: [enrollments.userId, enrollments.courseId],
    }).onDelete("cascade"),
    check("lesson_progress_lesson_id_check", sql`${t.lessonId} <> ''`),
    check(
      "lesson_progress_status_check",
      sql`${t.status} IN ${inList("lesson_progress_status_check", LESSON_PROGRESS_STATUSES)}`,
    ),
    check(
      "lesson_progress_completed_check",
      sql`(${t.status} = 'completed') = (${t.completedAt} IS NOT NULL)`,
    ),
  ],
);

export const attempts = pgTable(
  "attempts",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: text("user_id").notNull(),
    courseId: text("course_id").notNull(),
    lessonId: text("lesson_id").notNull(),
    status: text("status", { enum: ATTEMPT_STATUSES }).notNull().default("running"),
    /** Relative to the transcript store root (backlog 12); NULL means no transcript. */
    transcriptPath: text("transcript_path"),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull().defaultNow(),
    finishedAt: timestamp("finished_at", { withTimezone: true }),
  },
  (t) => [
    foreignKey({
      name: "attempts_lesson_progress_fk",
      columns: [t.userId, t.courseId, t.lessonId],
      foreignColumns: [lessonProgress.userId, lessonProgress.courseId, lessonProgress.lessonId],
    }).onDelete("cascade"),
    // Attempt history per lesson, and the referencing side of the cascade (Postgres does not index it).
    index("attempts_lesson_started_idx").on(t.userId, t.courseId, t.lessonId, t.startedAt),
    check(
      "attempts_status_check",
      sql`${t.status} IN ${inList("attempts_status_check", ATTEMPT_STATUSES)}`,
    ),
    check("attempts_finished_check", sql`(${t.status} = 'running') = (${t.finishedAt} IS NULL)`),
    // Defence in depth only: the transcript reader still confines realpath(root + path) under the
    // root. Every segment starts with a letter or digit, which rules out "." and ".." anywhere; both
    // anchors are load-bearing. The pattern has no backslash, so it reaches the SQL file unchanged.
    check(
      "attempts_transcript_path_check",
      sql`${t.transcriptPath} ~ '^[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*/?$'`,
    ),
  ],
);

export const checkResults = pgTable(
  "check_results",
  {
    attemptId: uuid("attempt_id").notNull(),
    checkId: text("check_id").notNull(),
    // Stored because the lesson file may change later, and history must keep what was graded.
    checkKind: text("check_kind").$type<Check["kind"]>().notNull(),
    status: text("status", { enum: CHECK_RESULT_STATUSES }).notNull(),
    score: doublePrecision("score"),
    /** Per-kind payload, validated by the writer. Never grader secrets (ADR-0007, decision 5). */
    details: jsonb("details").$type<unknown>(),
    durationMs: integer("duration_ms"),
    /** numeric(12,6): pg returns it as a string. */
    costUsd: numeric("cost_usd", { precision: 12, scale: 6 }),
    createdAt: createdAt(),
  },
  (t) => [
    primaryKey({ name: "check_results_pkey", columns: [t.attemptId, t.checkId] }),
    foreignKey({
      name: "check_results_attempt_id_fk",
      columns: [t.attemptId],
      foreignColumns: [attempts.id],
    }).onDelete("cascade"),
    check("check_results_check_id_check", sql`${t.checkId} <> ''`),
    check(
      "check_results_check_kind_check",
      sql`${t.checkKind} IN ${inList("check_results_check_kind_check", CHECK_KINDS)}`,
    ),
    check(
      "check_results_status_check",
      sql`${t.status} IN ${inList("check_results_status_check", CHECK_RESULT_STATUSES)}`,
    ),
    check("check_results_score_check", sql`${t.score} >= 0 AND ${t.score} <= 1`),
    check("check_results_duration_check", sql`${t.durationMs} >= 0`),
    check("check_results_cost_check", sql`${t.costUsd} >= 0`),
  ],
);

export const mentorReviews = pgTable(
  "mentor_reviews",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    attemptId: uuid("attempt_id").notNull(),
    // No FK: the review may start before the check result row exists. NULL = whole-attempt review.
    checkId: text("check_id"),
    status: text("status", { enum: MENTOR_REVIEW_STATUSES }).notNull().default("pending"),
    body: text("body"),
    costUsd: numeric("cost_usd", { precision: 12, scale: 6 }),
    createdAt: createdAt(),
    completedAt: timestamp("completed_at", { withTimezone: true }),
  },
  (t) => [
    foreignKey({
      name: "mentor_reviews_attempt_id_fk",
      columns: [t.attemptId],
      foreignColumns: [attempts.id],
    }).onDelete("cascade"),
    index("mentor_reviews_attempt_created_idx").on(t.attemptId, t.createdAt),
    check(
      "mentor_reviews_status_check",
      sql`${t.status} IN ${inList("mentor_reviews_status_check", MENTOR_REVIEW_STATUSES)}`,
    ),
    check("mentor_reviews_cost_check", sql`${t.costUsd} >= 0`),
    check(
      "mentor_reviews_completed_check",
      sql`(${t.status} = 'pending') = (${t.completedAt} IS NULL)`,
    ),
  ],
);
