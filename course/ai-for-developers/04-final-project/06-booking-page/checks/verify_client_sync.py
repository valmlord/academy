"""client-in-sync (design #44, 4.L6): the committed client types are what the contract generates today.

1. frontend/package-lock.json pins openapi-typescript 7.13.0 and typescript 5.9.3 exactly: the generated bytes
   depend on the generator and on the TypeScript printer it uses.
2. The grader compiles the learner's contract/ itself (the L2 pipeline of 7.2: copy step, exact JS allowlist,
   the grader's options), then runs the image's openapi-typescript (7.13.0 with typescript 5.9.3) in a child
   on that document.
3. The output must equal frontend/app/api/schema.d.ts byte for byte after CRLF is turned into LF.
No learner code runs: the lock file and schema.d.ts are read, contract/ is compiled by the grader, and
nothing from frontend/node_modules is used.
"""

from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

CHECKS_DIR = Path(__file__).resolve().parent
# `python3 -I` leaves the script directory off sys.path; the shared modules live next to this script.
sys.path.insert(0, str(CHECKS_DIR))

import final_runtime as runtime  # noqa: E402

ALLOWLIST = CHECKS_DIR / "data" / "tsp-js-allowlist.json"
LOCK = "frontend/package-lock.json"
SCHEMA = "frontend/app/api/schema.d.ts"
PINS = {
    "openapi-typescript": ("7.13.0", "от версии генератора зависят байты schema.d.ts, а проверка генерирует его версией 7.13.0"),
    "typescript": ("5.9.3", "openapi-typescript печатает типы компилятором TypeScript, и от его версии зависят байты schema.d.ts"),
}
COMPILE_TIMEOUT_SEC = 90
GENERATE_TIMEOUT_SEC = 60


def regular_file(workspace: Path, relative: str) -> tuple[bytes | None, str | None]:
    path = workspace / relative
    if path.is_symlink():
        return None, f"{relative}: символическая ссылка не допускается, нужен обычный файл"
    if not path.is_file():
        return None, None
    return path.read_bytes(), None


def lock_problems(workspace: Path) -> list[str]:
    data, refused = regular_file(workspace, LOCK)
    if refused:
        return [refused]
    if data is None:
        return [f"нет файла {LOCK}: версии зависимостей фронтенда закрепляет он (его пишет npm install)"]
    try:
        lock = runtime.strict_json(data.decode("utf-8"))
    except (UnicodeDecodeError, runtime.StrictJsonError) as error:
        return [f"{LOCK}: не JSON ({error})"]
    packages = lock.get("packages") if isinstance(lock, dict) else None
    if not isinstance(packages, dict):
        return [f"{LOCK}: нет раздела packages (нужен lockfileVersion 3, его пишет npm 7 и новее)"]
    problems = []
    for name, (version, reason) in PINS.items():
        entry = packages.get(f"node_modules/{name}")
        found = entry.get("version") if isinstance(entry, dict) else None
        if found != version:
            shown = f"версии {found}" if isinstance(found, str) else "нет"
            problems.append(f"{LOCK}: {name} {shown}, а нужен ровно {version}: {reason}")
    return problems


def first_difference(committed: list[str], generated: list[str]) -> str:
    for number, (have, want) in enumerate(zip(committed, generated), start=1):
        if have != want:
            return f"строка {number}:\n  в файле:   {have[:200]}\n  генерация: {want[:200]}"
    number = min(len(committed), len(generated)) + 1
    if len(committed) > len(generated):
        return f"строка {number}: в файле лишние строки после конца генерации ({committed[number - 1][:200]})"
    return f"строка {number}: в файле нет строк, которые есть в генерации ({generated[number - 1][:200]})"


def generate(layout: runtime.Layout, root: Path, document: str) -> bytes:
    work = Path(tempfile.mkdtemp(prefix="oats-", dir=root))
    source, target = work / "openapi.json", work / "schema.d.ts"
    source.write_text(document, encoding="utf-8")
    env = {"PATH": f"{Path(layout.node).parent}:/usr/bin:/bin", "HOME": str(work), "TMPDIR": str(work)}
    result = runtime.run_child([runtime.tool_path(layout, "openapi-typescript"), str(source), "-o", str(target)], work, env,
                               GENERATE_TIMEOUT_SEC)
    if result.exit_code != 0 or not target.is_file():
        raise runtime.GraderError(f"openapi-typescript образа не сгенерировал типы ({result.tail(5)})")
    return target.read_bytes()


def evaluate(workspace: Path) -> tuple[list[str], str]:
    layout = runtime.load_layout()
    runtime.self_check_tools(layout, ("node", "openapi-typescript"))
    problems = lock_problems(workspace)
    committed, refused = regular_file(workspace, SCHEMA)
    if refused:
        problems.append(refused)
    elif committed is None:
        problems.append(f"нет файла {SCHEMA}: его создаёт make gen из contract/, и он хранится в репозитории")
    root = runtime.grader_root(workspace)
    try:
        try:
            outcome = runtime.compile_contract(workspace / "contract", root, layout, ALLOWLIST, COMPILE_TIMEOUT_SEC)
        except runtime.ContractCopyError as error:
            return problems + [str(error)], ""
        record = outcome.record
        document = record.get("document")
        if record.get("timedOut") or record.get("crashed") or record.get("refusedImports") or record.get("badContexts") \
                or record.get("hasError") or not isinstance(document, str):
            return problems + ["contract/ не компилируется так, как его компилирует contract-matches (урок 2): "
                               "сначала добейтесь, чтобы прошла она"], ""
        if problems or committed is None:
            return problems, ""
        generated = generate(layout, root, document)
        have = committed.replace(b"\r\n", b"\n").decode("utf-8", "replace").split("\n")
        want = generated.replace(b"\r\n", b"\n").decode("utf-8", "replace").split("\n")
        if have != want:
            return [f"{SCHEMA} не совпадает с тем, что openapi-typescript 7.13.0 генерирует из вашего contract/ сейчас. "
                    f"Первая разница, {first_difference(have, want)}\n"
                    "Запустите make gen и закоммитьте результат; править сгенерированный файл руками нельзя."], ""
        return [], (f"Пройдено: {SCHEMA} совпадает с тем, что openapi-typescript 7.13.0 (typescript 5.9.3) генерирует из "
                    f"вашего contract/ ({len(want)} строк), версии закреплены в {LOCK}.")
    finally:
        shutil.rmtree(root, ignore_errors=True)


def main() -> int:
    runtime.make_grader_non_dumpable()
    try:
        problems, passed = evaluate(Path.cwd().resolve())
    except runtime.GraderError as error:
        print(error)
        return 1
    if problems:
        print("\n".join(problems))
        return 1
    print(passed)
    return 0


if __name__ == "__main__":
    sys.exit(main())
