"""Generate src/invoices/generated/invoice_schema.py from the JSON schema."""

import json
import shutil
import sys
from pathlib import Path

HEADER = "# Generated by scripts/codegen.py from {schema}. Do not edit: run `make codegen`.\n"
PY_TYPES = {"integer": "int", "string": "str"}


def main(schema_path: str, out_dir: str) -> None:
    schema = json.loads(Path(schema_path).read_text(encoding="utf-8"))
    out = Path(out_dir)
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    (out / "__init__.py").write_text(HEADER.format(schema=schema_path), encoding="utf-8")
    lines = [HEADER.format(schema=schema_path), "from dataclasses import dataclass\n\n\n"]
    lines.append("@dataclass(frozen=True)\nclass InvoiceRecord:\n")
    for name, spec in schema["properties"].items():
        lines.append(f"    {name}: {PY_TYPES[spec['type']]}\n")
    lines.append(f"\n\nREQUIRED_FIELDS = {tuple(schema['required'])!r}\n")
    (out / "invoice_schema.py").write_text("".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
